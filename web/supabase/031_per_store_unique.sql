-- ===========================================================================
-- 031 - names are unique per store, and the photo sweep sees every photo
--       (offline-v2 Phase 0b, docs/offline-v2/design.md section 4.1)
--
-- 1) PER-STORE UNIQUENESS. 000 made inventory.sku and the name of lens_types,
--    frame_types and frame_colors unique across the WHOLE database. 008 then
--    made every one of those tables per store, but the constraints stayed
--    global: a second store cannot add a product with a SKU another store
--    uses, or a lens type called "Single vision" once the first store has
--    one. Each becomes unique per store. The per-store index is created
--    BEFORE the global constraint is dropped, so uniqueness never lapses, and
--    a database that satisfied the global rule satisfies the per-store one,
--    so no data needs fixing and the index build cannot fail. (030 did the
--    same for invoice numbers.) A blank SKU is stored as "no SKU" (NULL) - the
--    app already sends NULL for an empty field - so blanks never collide.
--
-- 2) SETTINGS. settings.key is global too, but the app upserts a setting
--    with ON CONFLICT (key) today, so that constraint must stay until every
--    device runs the new app (offline-v2 migration 032 drops it). This adds
--    the per-store unique (store_id, key) the new app upserts against; both
--    hold for a single store, so nothing changes for it.
--
-- 3) THE PHOTO SWEEP COULD DELETE LIVE PHOTOS. The platform page's "Scan
--    storage" built its keep-list with one unpaged select of every sale's
--    photo paths. PostgREST caps a response (1,000 rows by default), so past
--    that many sales the keep-list was silently cut short and photos that
--    real invoices still point at were listed as orphans - one click on
--    Delete away from being lost. referenced_image_paths() returns a store's
--    referenced paths in keyset pages that the app walks to the end. (The app
--    also stops listing files younger than 14 days: a photo uploaded at cart
--    entry has no sale row until checkout.)
--
-- 4) THE STAFF LIMIT COUNTS ACTIVE STAFF. create-user now counts only active
--    staff, so a switched-off person frees a seat; set_staff_access therefore
--    checks the limit when it switches someone back on.
--
-- Idempotent: safe to paste more than once.
-- HOW TO RUN: Supabase Dashboard -> SQL Editor -> paste -> Run (after 030),
-- then deploy the matching web app. See RELEASE_031.md.
-- ===========================================================================
begin;

-- ============================================================
-- 1) a blank SKU is no SKU
-- ============================================================
update public.inventory set sku = null where sku is not null and btrim(sku) = '';

-- ============================================================
-- 2) per-store unique: index first, then the global constraint
-- ============================================================
create unique index if not exists inventory_store_sku_key
  on public.inventory (store_id, sku);
create unique index if not exists lens_types_store_name_key
  on public.lens_types (store_id, name);
create unique index if not exists frame_types_store_name_key
  on public.frame_types (store_id, name);
create unique index if not exists frame_colors_store_name_key
  on public.frame_colors (store_id, name);

-- The global constraints were declared inline in 000 (`sku TEXT UNIQUE`,
-- `name TEXT NOT NULL UNIQUE`), so their names were generated by PostgreSQL
-- and are not guaranteed. Find each by table and column instead: the
-- single-column UNIQUE constraint on exactly that column.
do $$
declare
  t record;
  v_con text;
begin
  for t in
    select * from (values
      ('inventory', 'sku'),
      ('lens_types', 'name'),
      ('frame_types', 'name'),
      ('frame_colors', 'name')) as v(tbl, col)
  loop
    for v_con in
      select c.conname
        from pg_constraint c
        join pg_attribute a
          on a.attrelid = c.conrelid and a.attnum = c.conkey[1]
       where c.conrelid = format('public.%I', t.tbl)::regclass
         and c.contype = 'u'
         and array_length(c.conkey, 1) = 1
         and a.attname = t.col
    loop
      execute format('alter table public.%I drop constraint %I', t.tbl, v_con);
      raise notice '031: dropped global unique % on %.%', v_con, t.tbl, t.col;
    end loop;
  end loop;
end $$;

-- ============================================================
-- 3) settings: per-store key, alongside the global one for now
-- ============================================================
create unique index if not exists settings_store_key_key
  on public.settings (store_id, key);

-- ============================================================
-- 4) referenced_image_paths: the photo sweep's keep-list, paged
-- ============================================================
-- Every non-empty rx/frame photo path that a sale of p_store references, or
-- that ANY sale references inside p_store's folder (the sweep must never
-- delete a file some invoice points at, whatever store that invoice is in).
-- Keyset paged: pass the last path of the previous page as p_after, stop
-- when a page is shorter than p_limit. Ordered with the "C" collation so the
-- order and the > comparison agree on every server locale.
create or replace function public.referenced_image_paths(
  p_store uuid,
  p_after text default null,
  p_limit integer default 1000
)
returns table (path text)
language plpgsql stable security definer set search_path = public as $$
declare
  v_prefix text := 'store/' || p_store::text || '/';
  v_limit  integer := least(greatest(coalesce(p_limit, 1000), 1), 1000);
begin
  if not public.is_platform_admin() then
    raise exception 'platform admin only' using errcode = '42501';
  end if;
  return query
    select x.p
      from (
        select btrim(s.rx_image_path) as p
          from public.sales s
         where s.store_id = p_store or s.rx_image_path like v_prefix || '%'
        union
        select btrim(s.frame_image_path)
          from public.sales s
         where s.store_id = p_store or s.frame_image_path like v_prefix || '%'
      ) x
     where x.p is not null and x.p <> ''
       and (p_after is null or x.p collate "C" > p_after collate "C")
     order by x.p collate "C"
     limit v_limit;
end $$;

revoke execute on function public.referenced_image_paths(uuid, text, integer) from public, anon;
grant execute on function public.referenced_image_paths(uuid, text, integer) to authenticated;

-- ============================================================
-- 5) the staff limit counts ACTIVE staff, so switching on is checked too
-- ============================================================
-- create-user now counts only active staff against store_licenses.max_staff
-- (a switched-off person holds no seat, so a replacement can be added). That
-- opens one way past the limit: switch someone off, add a replacement, then
-- switch the first person back on. set_staff_access (029) never looked at the
-- limit, because before this every row counted whether active or not. It now
-- refuses switching a person ON when the store is already at its limit.
-- Body otherwise identical to 029:166-181; the store row lock it already
-- takes serialises two managers doing this at once.
create or replace function public.set_staff_access(p_user uuid, p_role uuid, p_active boolean) returns void
language plpgsql security definer set search_path = public as $$
declare v public.users; v_max integer; v_active integer;
begin
  -- Serialise management changes in a store, including demotions.
  perform 1 from public.stores where id=public.auth_store_id() for update;
  select * into v from public.users where id=p_user for update;
  if not found then raise exception 'Employee not found'; end if;
  perform public.require_staff_editor(v.store_id);
  if p_user=auth.uid() then raise exception 'Ask another administrator to change your own access'; end if;
  if exists(select 1 from public.platform_admins where auth_uid=p_user) then raise exception 'Platform accounts are managed separately'; end if;
  if public.is_store_admin(p_user) and not public.is_store_admin() then raise exception 'Only an administrator can change administrator access'; end if;
  if p_role is not null and not public.can_assign_role(p_role,v.store_id) then raise exception 'Cannot assign this position'; end if;
  if p_active is null then raise exception 'Active state is required'; end if;
  if p_active is distinct from v.is_active then perform public.require_perm('staff.delete'); end if;
  if p_active and v.is_active is not true then
    select l.max_staff into v_max from public.store_licenses l where l.store_id = v.store_id;
    if v_max is not null then
      select count(*) into v_active from public.users u
       where u.store_id = v.store_id and u.is_active is true;
      if v_active >= v_max then
        raise exception 'Staff limit reached (%/%): switch someone off first', v_active, v_max;
      end if;
    end if;
  end if;
  update public.users set role_id=p_role,is_active=p_active where id=p_user;
end $$;

revoke execute on function public.set_staff_access(uuid,uuid,boolean) from public, anon;
grant execute on function public.set_staff_access(uuid,uuid,boolean) to authenticated;

-- ============================================================
-- 6) stamp THIS migration (020 makes an unstamped file a red build)
-- ============================================================
select public.record_schema_version(31, 'per-store unique sku and lens/frame type and colour names, per-store settings key (global key kept until 032), paged referenced_image_paths for the photo sweep, staff limit checked when switching staff on');
commit;
